def generate_learning_card(test_type: str, test_name_zh: str = "") -> Optional[LearningCard]:
    """根据检验类型生成教学卡片。"""
    entry = LEARNING_DB.get(test_type)
    if entry is None:
        return None

    return LearningCard(
        test_type=test_type,
        test_name_zh=test_name_zh,
        decision_logic=entry.get("decision", ""),
        spss_path=entry.get("spss_path", ""),
        spss_steps=entry.get("spss_steps", []),
        methodology_steps=entry.get("methodology", []),
        common_mistakes=entry.get("mistakes", []),
        key_concepts=entry.get("concepts", {}),
    )


def format_learning_card_text(card: LearningCard) -> str:
    """将教学卡片格式化为可读文本（用于 Streamlit 展示）。"""
    if card is None:
        return ""

    sections = []

    sections.append(f"## 📖 方法学习卡片：{card.test_name_zh}")

    if card.decision_logic:
        sections.append(f"### 🧭 为什么选这个方法？\n{card.decision_logic}")

    if card.methodology_steps:
        steps_text = "\n".join(card.methodology_steps)
        sections.append(f"### 📋 分析步骤（通用流程）\n{steps_text}")

    if card.spss_path:
        spss_text = f"**菜单路径：** {card.spss_path}\n"
        if card.spss_steps:
            spss_text += "\n".join(f"  {i+1}. {s}" for i, s in enumerate(card.spss_steps))
        sections.append(f"### 🖥️ SPSS 怎么操作\n{spss_text}")

    if card.common_mistakes:
        mistakes_text = "\n".join(f"  ❌ {m}" for m in card.common_mistakes)
        sections.append(f"### ⚠️ 常见误区\n{mistakes_text}")

    if card.key_concepts:
        concepts_text = "\n".join(f"  • **{k}**：{v}" for k, v in card.key_concepts.items())
        sections.append(f"### 💡 关键概念\n{concepts_text}")

    return "\n\n".join(sections)
