def _apply_semantic_negation(text: str) -> str:
    """对正向题目进行语义否定，生成自然的中文反向题。

    策略优先级：
    1. 精确匹配语义否定对（最自然）
    2. 在谓语前插入否定词（次选）
    3. 整句反转（降级）
    """
    # 策略1: 语义否定替换
    for positive_word, negative_word in SEMANTIC_NEGATIONS:
        if positive_word in text:
            return text.replace(positive_word, negative_word, 1)

    # 策略2: 在主要动词前插入否定
    # 找到主要谓语位置（通常在"我"之后）
    negation_insertions = [
        ("我通常会", "我通常不会"),
        ("我能够", "我不能够"),
        ("我会", "我不会"),
        ("我常常", "我很少"),
        ("我发现", "我没有发现"),
        ("我认为", "我不认为"),
    ]
    for pos, neg in negation_insertions:
        if pos in text:
            return text.replace(pos, neg, 1)

    # 策略3: 在主语后直接加否定
    if text.startswith("我"):
        return text[:1] + "并不" + text[1:]

    return "我不认为" + text


