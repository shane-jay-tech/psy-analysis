def _fill_template(
    tmpl: str,
    dim_desc: str,
    construct: str,
    dim_name: str,
    domain: str = "",
) -> str:
    """上下文感知的模板填充。

    根据槽位类型选择领域专用词汇，而非简单字符串替换。
    """
    # 获取领域词汇表
    patterns = DOMAIN_SENTENCE_PATTERNS.get(domain, _DEFAULT_PATTERNS)
    vocab = patterns.get("vocabulary", _DEFAULT_PATTERNS["vocabulary"])

    text = tmpl
    dim_name_short = dim_name.replace(f"{construct}的", "").replace(f"的{construct}", "")

    # ---- 智能槽位填充 ----

    # {认知} → 认知/信念类描述
    if "{认知}" in text:
        options = vocab.get("认知", ["这方面对自己有信心"])
        text = text.replace("{认知}", _pick(options, dim_desc))

    # {行为} → 行为表现类描述
    if "{行为}" in text:
        options = vocab.get("行为", ["积极应对"])
        text = text.replace("{行为}", _pick(options, dim_desc))

    # {情感} → 情感体验类描述
    if "{情感}" in text:
        options = vocab.get("情感", ["积极感受"])
        text = text.replace("{情感}", _pick(options, dim_desc))

    # {态度} → 态度评价类描述
    if "{态度}" in text:
        options = vocab.get("态度", ["积极的"])
        text = text.replace("{态度}", _pick(options, dim_desc) if options else "积极的")

    # {维度名} → 维度名称
    text = text.replace("{维度名}", dim_name_short)

    # ---- 降级：兼容旧版槽位 ----
    text = text.replace("[维度描述]", dim_desc)
    text = text.replace("[行为/感受描述]", dim_desc)
    text = text.replace("[行为描述]", dim_desc)
    text = text.replace("[感受描述]", dim_desc)
    text = text.replace("[负面感受描述]", dim_desc)
    text = text.replace("[负面反应描述]", dim_desc)
    text = text.replace("[积极反应]", f"积极应对{dim_desc}")
    text = text.replace("[正面反应描述]", "保持镇定和理性")
    text = text.replace("[评价对象]", dim_desc)
    text = text.replace("[积极形容词]", "积极")
    text = text.replace("[消极形容词]", "消极")
    text = text.replace("[情境描述]", f"面对{dim_desc}相关的情境")
    text = text.replace("[反应描述]", f"积极应对{dim_desc}")
    if "[时间段]" in text and "最近" not in text:
        text = text.replace("[时间段]", "一周")
    if "[描述]" in text:
        text = text.replace("[描述]", f"对{dim_desc}有帮助")
    if "[不行为描述]" in text:
        text = text.replace("[不行为描述]", f"不去{dim_desc}")

    return text


def _pick(options: list, seed: str = "") -> str:
    """从选项列表中基于种子的确定性选择（保证同一维度内用词一致）"""
    if not options:
        return seed
    idx = hash(seed) % len(options)
    return options[idx]


def generate_items_for_dimension(
    dimension: dict,
    template: dict,
    construct_name: str,
    start_index: int,
    reverse_ratio: float = 0.25,
    domain: str = "",
) -> list:
    """
    为一个维度生成题目列表。

    v2.0 改进：使用领域专用句型 + 语义反向生成。
    """
    n_items = dimension.get("item_count", 5)
    n_reverse = max(1, int(n_items * reverse_ratio))
    n_positive = n_items - n_reverse

    dim_name = dimension["name"]
    dim_desc = dimension["desc"]

    # 获取领域句型
    patterns = DOMAIN_SENTENCE_PATTERNS.get(domain, _DEFAULT_PATTERNS)
    pos_patterns = patterns.get("positive", _DEFAULT_PATTERNS["positive"])
    neg_patterns = patterns.get("reverse", _DEFAULT_PATTERNS["reverse"])

    items = []

    # 生成正向题
    for i in range(n_positive):
        tmpl = pos_patterns[i % len(pos_patterns)]
        text = _fill_template(tmpl, dim_desc, construct_name, dim_name, domain)
        items.append({
            "index": start_index + len(items),
            "text": text,
            "reverse": False,
            "dimension": dim_name,
        })

    # 生成反向题（语义否定）
    for i in range(n_reverse):
        if neg_patterns:
            # 优先使用预设反向句型
            tmpl = neg_patterns[i % len(neg_patterns)]
            text = _fill_template(tmpl, dim_desc, construct_name, dim_name, domain)
        else:
            # 降级：对正向句型做语义否定
            tmpl = pos_patterns[-(i + 1) % len(pos_patterns)]
            text = _fill_template(tmpl, dim_desc, construct_name, dim_name, domain)
            text = _apply_semantic_negation(text)

        items.append({
            "index": start_index + len(items),
            "text": text,
            "reverse": True,
            "dimension": dim_name,
        })

    return items
